// Streaming PRD generation function
async function generateStreamingPRD(req: any, res: any, timeout: NodeJS.Timeout) {
  try {
    const { prompt, projectData, pmFormData } = req.body;

    // Send initial response
    res.write(`data: ${JSON.stringify({
      type: 'start',
      message: 'Starting PRD generation...'
    })}\n\n`);

    // Generate PRD using the Grok service
    const result = await grokPRDService.generatePRD({
      prompt,
      projectData,
      pmFormData
    });

    if (!result || !result.content) {
      throw new Error('No content generated');
    }

    // Simulate streaming by sending content in chunks
    const content = result.content;
    const chunkSize = 100; // Characters per chunk
    let index = 0;

    const sendChunk = () => {
      if (index < content.length) {
        const chunk = content.slice(index, index + chunkSize);
        index += chunkSize;

        res.write(`data: ${JSON.stringify({
          type: 'content',
          content: chunk,
          progress: Math.min(95, (index / content.length) * 100)
        })}\n\n`);

        // Send next chunk after a short delay
        setTimeout(sendChunk, 50);
      } else {
        // Send completion
        res.write(`data: ${JSON.stringify({
          type: 'complete',
          content: '',
          progress: 100,
          metadata: result.metadata
        })}\n\n`);

        clearTimeout(timeout);
        res.end();
      }
    };

    // Start sending chunks
    sendChunk();

  } catch (error) {
    console.error('❌ Streaming PRD generation error:', error);
    
    res.write(`data: ${JSON.stringify({
      type: 'error',
      error: error instanceof Error ? error.message : 'Failed to generate PRD'
    })}\n\n`);

    clearTimeout(timeout);
    res.end();
  }
}

export default router;
