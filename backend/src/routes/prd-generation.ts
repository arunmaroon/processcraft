// POST /api/prd-generation/generate - Generate PRD using Claude 3.5 Sonnet (Primary)
router.post('/generate', async (req, res) => {
  // Set timeout for the request
  const timeout = setTimeout(() => {
    if (!res.headersSent) {
      res.status(408).json({
        success: false,
        error: 'Request timeout - PRD generation took too long',
        content: 'The PRD generation request timed out. Please try again with a simpler prompt.',
        metadata: {
          generatedAt: new Date().toISOString(),
          generatedBy: 'Timeout Handler',
          confidence: 0,
          source: 'timeout'
        }
      });
    }
  }, 120000); // 2 minute timeout

  try {
    const { prompt, projectData, pmFormData } = req.body;

    console.log('🚀 Generating PRD with Claude 3.5 Sonnet...');
    console.log('Project:', projectData?.name);
    console.log('PM Data available:', !!pmFormData);
    console.log('🔑 Claude API Key available:', process.env.CLAUDE_API_KEY ? 'YES' : 'NO');

    // Check if streaming is requested
    const isStreaming = req.headers.accept?.includes('text/stream') || req.query.stream === 'true';

    if (isStreaming) {
      // Set up streaming response
      res.setHeader('Content-Type', 'text/stream');
      res.setHeader('Cache-Control', 'no-cache');
      res.setHeader('Connection', 'keep-alive');
      res.setHeader('Access-Control-Allow-Origin', '*');
      res.setHeader('Access-Control-Allow-Headers', 'Cache-Control');

      // Generate PRD with streaming
      await generateStreamingPRD(req, res, timeout);
      return;
    }

    // Use Grok PRD Service for AI-powered PRD generation (Primary)
    const result = await grokPRDService.generatePRD({
      prompt,
      projectData,
      pmFormData
    });

    console.log('✅ PRD Generation completed');
    console.log('Generated by:', result.metadata.generatedBy);
    console.log('Confidence:', result.metadata.confidence);
    console.log('Source:', result.metadata.source);
    console.log('Content length:', result.content?.length || 0);

    // Ensure we always return a valid JSON response
    if (!result || typeof result !== 'object') {
      console.error('❌ Invalid result object:', result);
      return res.status(500).json({
        success: false,
        error: 'Invalid response from PRD service',
        content: 'Failed to generate PRD. Please try again.',
        metadata: {
          generatedAt: new Date().toISOString(),
          generatedBy: 'Error Handler',
          confidence: 0,
          source: 'error'
        }
      });
    }

    clearTimeout(timeout);
    res.json(result);

  } catch (error) {
    clearTimeout(timeout);
    console.error('❌ Error generating PRD:', error);
    
    // Fallback to Grok if Claude fails
    try {
      console.log('🔄 Falling back to Grok AI...');
      const grokResult = await grokPRDService.generatePRD({
        prompt: req.body.prompt,
        projectData: req.body.projectData,
        pmFormData: req.body.pmFormData
      });
      
      if (grokResult.success) {
        clearTimeout(timeout);
        return res.json(grokResult);
      }
    } catch (grokError) {
      console.error('❌ Grok fallback also failed:', grokError);
    }
    
    // Fallback to OpenAI if both Claude and Grok fail
    if (openai) {
      try {
        console.log('🔄 Falling back to OpenAI...');
        
        const enhancedPrompt = `You are an expert Product Manager and technical writer. Generate a comprehensive Product Requirements Document (PRD) based on the following information:

${req.body.prompt}

Please generate a professional PRD following Carlin Yuen's framework with:
1. Clear problem statement and opportunity
2. Target users and use cases
3. Current state and competitive landscape
4. Proposed solution with elevator pitch
5. Goals and measurable outcomes
6. Prioritized functional requirements
7. Success metrics and KPIs
8. Technical requirements and constraints
9. Risk assessment
10. Implementation timeline

Format the response as a well-structured markdown document with clear headings and actionable insights.`;

        const completion = await openai.chat.completions.create({
          model: "gpt-4",
          messages: [
            {
              role: "system",
              content: "You are an expert Product Manager and technical writer specializing in creating comprehensive Product Requirements Documents. You follow Carlin Yuen's PRD framework and create clear, actionable, and stakeholder-ready documents."
            },
            {
              role: "user",
              content: enhancedPrompt
            }
          ],
          max_tokens: 4000,
          temperature: 0.7,
        });

        const generatedContent = completion.choices[0]?.message?.content || '';

        clearTimeout(timeout);
        return res.json({
          success: true,
          content: generatedContent,
          metadata: {
            generatedAt: new Date().toISOString(),
            generatedBy: 'OpenAI GPT-4 (Fallback)',
            confidence: 0.9,
            source: 'openai-fallback',
            model: 'gpt-4',
            tokens: completion.usage?.total_tokens || 0
          }
        });

      } catch (openaiError) {
        console.error('❌ OpenAI fallback also failed:', openaiError);
      }
    }
    
    // Final fallback to basic generation
    clearTimeout(timeout);
    res.json({
      success: false,
      error: error instanceof Error ? error.message : 'Failed to generate PRD',
      content: generateFallbackPRD(req.body.projectData, req.body.pmFormData),
      metadata: {
        generatedAt: new Date().toISOString(),
        generatedBy: 'Basic Fallback Generator',
        confidence: 0.5,
        source: 'fallback-error'
      }
    });
  }
});

